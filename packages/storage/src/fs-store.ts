import { createHash, randomUUID } from 'node:crypto'
import { createReadStream, createWriteStream } from 'node:fs'
import { mkdir, rename, rm, stat } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import type { Readable } from 'node:stream'
import { Transform } from 'node:stream'
import { pipeline } from 'node:stream/promises'

/** Thrown when an upload exceeds the configured size limit. */
export class TooLargeError extends Error {
  override name = 'TooLargeError'
  constructor(readonly maxBytes: number) {
    super(`object larger than ${maxBytes} bytes`)
  }
}

/** An uploaded object in a temporary location: checked first, then committed or discarded. */
export interface PendingObject {
  sizeBytes: number
  sha256: Buffer
  /** The first bytes of the content, for type detection (magic numbers). */
  head: Buffer
  /** Moves the object to its final key. */
  commit(key: string): Promise<void>
  /** Removes the temporary file. Safe to call more than once and after commit. */
  discard(): Promise<void>
}

/**
 * Storage for uploaded files (ADR 0004). Keys are generated by the server
 * (e.g. `<tenant>/files/<uuid>`), never taken from user input.
 */
export interface ObjectStore {
  /** Streams the content into a temporary object, counting bytes and hashing on the way. */
  receive(source: Readable, options: { maxBytes: number }): Promise<PendingObject>
  read(key: string): Readable
  size(key: string): Promise<number | null>
  delete(key: string): Promise<void>
}

const KEY_PATTERN = /^[a-z0-9][a-z0-9_-]*(\/[a-z0-9][a-z0-9_-]*)*$/
const HEAD_BYTES = 4096

export function assertValidKey(key: string): void {
  if (!KEY_PATTERN.test(key) || key.length > 300) throw new Error(`invalid storage key: ${key}`)
}

/** Object store on the local file system (a Docker volume in production). */
export class FsObjectStore implements ObjectStore {
  constructor(private readonly root: string) {}

  private pathOf(key: string): string {
    assertValidKey(key)
    return join(this.root, 'objects', key)
  }

  async receive(source: Readable, { maxBytes }: { maxBytes: number }): Promise<PendingObject> {
    const tmpDir = join(this.root, 'tmp')
    await mkdir(tmpDir, { recursive: true })
    const tmpPath = join(tmpDir, randomUUID())
    const hash = createHash('sha256')
    const headChunks: Buffer[] = []
    let headLength = 0
    let size = 0
    const meter = new Transform({
      transform(chunk: Buffer, _encoding, callback) {
        size += chunk.length
        if (size > maxBytes) {
          callback(new TooLargeError(maxBytes))
          return
        }
        hash.update(chunk)
        if (headLength < HEAD_BYTES) {
          const part = chunk.subarray(0, HEAD_BYTES - headLength)
          headChunks.push(part)
          headLength += part.length
        }
        callback(null, chunk)
      },
    })
    try {
      await pipeline(source, meter, createWriteStream(tmpPath, { flags: 'wx', mode: 0o640 }))
    } catch (error) {
      source.resume()
      await rm(tmpPath, { force: true })
      throw error
    }
    let committed = false
    return {
      sizeBytes: size,
      sha256: hash.digest(),
      head: Buffer.concat(headChunks),
      commit: async (key: string) => {
        const target = this.pathOf(key)
        await mkdir(dirname(target), { recursive: true })
        await rename(tmpPath, target)
        committed = true
      },
      discard: async () => {
        if (!committed) await rm(tmpPath, { force: true })
      },
    }
  }

  read(key: string): Readable {
    return createReadStream(this.pathOf(key))
  }

  async size(key: string): Promise<number | null> {
    try {
      return (await stat(this.pathOf(key))).size
    } catch {
      return null
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathOf(key), { force: true })
  }
}
